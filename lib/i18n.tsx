type I18nContextValue = {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: string, fallback?: string) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

function getByPath(obj: Translations, path: string): string | undefined {
  const segments = path.split('.');
  let current: string | Translations | undefined = obj;

  for (const segment of segments) {
    if (!current || typeof current === 'string') return undefined;
    current = current[segment];
  }

  return typeof current === 'string' ? current : undefined;
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>('en');

  useEffect(() => {
    const stored = typeof window !== 'undefined' ? window.localStorage.getItem('splitwiser-language') : null;
    if (stored === 'it' || stored === 'en') {
      setLanguageState(stored);
      document.documentElement.lang = stored;
      return;
    }

    const browser = navigator.language?.toLowerCase() || 'en';
    const detected: Language = browser.startsWith('it') ? 'it' : 'en';
    setLanguageState(detected);
    document.documentElement.lang = detected;
  }, []);

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    if (typeof window !== 'undefined') {
      window.localStorage.setItem('splitwiser-language', lang);
    }
    document.documentElement.lang = lang;
  };

  const value = useMemo<I18nContextValue>(() => ({
    language,
    setLanguage,
    t: (key: string, fallback?: string) => {
      const own = getByPath(translations[language], key);
      if (own) return own;
      const fromEn = getByPath(translations.en, key);
      return fromEn || fallback || key;
    },
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    throw new Error('useI18n must be used within LanguageProvider');
  }
  return ctx;
}
